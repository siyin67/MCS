    $Size = [math]::Round((Get-Item $Out).Length / 1KB, 1)
    Write-Host ""
    Write-Host "=== Build OK ($Size KB) ==="
} else {
    Write-Host ""
    Write-Host "=== Build FAILED (exit $LASTEXITCODE) ==="
    exit $LASTEXITCODE
